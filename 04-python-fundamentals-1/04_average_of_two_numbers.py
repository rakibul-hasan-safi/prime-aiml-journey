# Lesson: Taking User Input / Average of 2 Nums
# Reading two numbers from the user, casting them to float, and printing their average

number1 = float(input("Enter the first number: "))
number2 = float(input("Enter the second number: "))
sum = number1 + number2
avg = sum/2

print ("The Avg of", number1, "and", number2, "is" , avg)

# Sample run:
# Enter the first number: 3
# Enter the second number: 2
# The Avg of 3.0 and 2.0 is 2.5
